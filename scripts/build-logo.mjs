// Builds the Nerogate logo from one source:
//  - outlines the wordmark from Hanken Grotesk 600 (opentype.js)
//  - writes src/components/brand/logoPaths.ts for the inline React logo
//  - writes public/brand/logo.svg, public/favicon.svg and the 500x500 PNG exports (resvg)
// Run: node scripts/build-logo.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import { Resvg } from '@resvg/resvg-js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const fontFile = path.join(root, 'node_modules/@fontsource/hanken-grotesk/files/hanken-grotesk-latin-600-normal.woff')
const font = opentype.parse(fs.readFileSync(fontFile).buffer.slice(0))

const INK = '#19140f'
const EMBER = '#c8400c'
const EMBER_LIGHT = '#ff7a33'

// Mark (36x36): a gate arch with an arrow leaving through it. XMR goes in, the asset comes out.
const MARK_ARCH = 'M7 33V17a11 11 0 0 1 22 0v16'
const MARK_ARROW = 'M13 27.5l9.5-9.5M15.5 18h7v7'

// Wordmark
const WORD = 'nerogate'
const FONT_SIZE = 31
const TRACKING = -0.015 * FONT_SIZE
const BASELINE = 28
const WORD_X = 43
let x = WORD_X
let d = ''
for (const ch of WORD) {
  const glyph = font.charToGlyph(ch)
  d += glyph.getPath(x, BASELINE, FONT_SIZE).toPathData(2)
  x += (glyph.advanceWidth / font.unitsPerEm) * FONT_SIZE + TRACKING
}
const WIDTH = Math.ceil(x - TRACKING + 1)
const HEIGHT = 36

const markSvg = (arch, arrow) =>
  `<path d="${MARK_ARCH}" fill="none" stroke="${arch}" stroke-width="4.6" stroke-linecap="round"/>` +
  `<path d="${MARK_ARROW}" fill="none" stroke="${arrow}" stroke-width="3.4" stroke-linecap="round" stroke-linejoin="round"/>`

const logoSvg = (arch, arrow, word, bg) => {
  const inner = markSvg(arch, arrow) + `<path d="${d}" fill="${word}"/>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}"${bg ? ` style="background:${bg}"` : ''}>${inner}</svg>`
}

// React path data
fs.mkdirSync(path.join(root, 'src/components/brand'), { recursive: true })
fs.writeFileSync(
  path.join(root, 'src/components/brand/logoPaths.ts'),
  `// Generated by scripts/build-logo.mjs. Do not edit by hand.\n` +
    `export const LOGO_WIDTH = ${WIDTH}\nexport const LOGO_HEIGHT = ${HEIGHT}\n` +
    `export const MARK_ARCH = '${MARK_ARCH}'\nexport const MARK_ARROW = '${MARK_ARROW}'\n` +
    `export const WORDMARK = '${d}'\n`,
)

// Source SVG + favicon
fs.mkdirSync(path.join(root, 'public/brand'), { recursive: true })
fs.writeFileSync(path.join(root, 'public/brand/logo.svg'), logoSvg(EMBER, INK, INK))
fs.writeFileSync(path.join(root, 'public/brand/logo-inverted.svg'), logoSvg(EMBER_LIGHT, '#ffffff', '#ffffff'))
fs.writeFileSync(
  path.join(root, 'public/favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 36 36"><style>.a{stroke:${EMBER}}.r{stroke:${INK}}@media (prefers-color-scheme:dark){.a{stroke:${EMBER_LIGHT}}.r{stroke:#fff}}</style>` +
    `<path class="a" d="${MARK_ARCH}" fill="none" stroke-width="4.6" stroke-linecap="round"/>` +
    `<path class="r" d="${MARK_ARROW}" fill="none" stroke-width="3.4" stroke-linecap="round" stroke-linejoin="round"/></svg>`,
)

// 500x500 PNG exports, logo centred with ~12% padding
const SIZE = 500
const PAD = SIZE * 0.12
const scale = (SIZE - PAD * 2) / WIDTH
const h = HEIGHT * scale
const square = (arch, arrow, word, bg) => {
  const inner = markSvg(arch, arrow) + `<path d="${d}" fill="${word}"/>`
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">` +
    (bg ? `<rect width="${SIZE}" height="${SIZE}" fill="${bg}"/>` : '') +
    `<g transform="translate(${PAD} ${(SIZE - h) / 2}) scale(${scale})">${inner}</g></svg>`
  )
}
const render = (svg, file) => {
  const png = new Resvg(svg, { fitTo: { mode: 'original' } }).render().asPng()
  fs.writeFileSync(path.join(root, 'public/brand', file), png)
}
render(square(EMBER_LIGHT, '#ffffff', '#ffffff', INK), 'logo-500.png')
render(square(EMBER, INK, INK, null), 'logo-500-transparent.png')

console.log(`logo ${WIDTH}x${HEIGHT}, wordmark path ${d.length} chars`)
